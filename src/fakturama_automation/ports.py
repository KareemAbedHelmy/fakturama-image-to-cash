"""Desktop contract. Search methods must return complete, stable observed results.

This contract is implemented by a simulator. A real Fakturama adapter is pending
Windows inspection; a generic UIA helper alone does not implement this contract.
"""

from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from typing import Literal, Protocol

from .domain import Address, Debtor, Item, OrderInput, Totals
from .matching import DebtorRow, PaymentRow, ProductRow, VatRow


@dataclass(frozen=True)
class Handle:
    editor_id: str
    number: str


@dataclass(frozen=True)
class Snapshot:
    number: str
    kind: Literal["Order", "Invoice"]
    reference: str
    order_date: date
    billing: Address
    delivery: Address
    items: tuple[Item, ...]
    totals: Totals
    price_mode: str
    vat_mode: str
    overall_discount: Decimal
    shipping_net: Decimal
    state: str
    source_order_number: str | None = None
    invoice_date: date | None = None
    service_date: date | None = None
    payment_method: str | None = None
    paid: bool = False
    payment_date: date | None = None
    payment_value: Decimal | None = None
    debtor_company: str = ""
    debtor_first_name: str = ""
    debtor_last_name: str = ""


class DesktopPort(Protocol):
    def preflight(self, source: OrderInput) -> None: ...
    def open_new_order(self) -> Handle: ...
    def assert_order_open(self, order: Handle) -> None: ...
    def configure_order(self, order: Handle, source: OrderInput) -> None: ...
    def search_debtors_from_order(self, order: Handle, query: str) -> tuple[DebtorRow, ...]: ...
    def cancel_selector(self) -> None: ...
    def select_debtor(self, order: Handle, row: DebtorRow) -> None: ...
    def verify_addresses(self, order: Handle, debtor: Debtor) -> None: ...
    def open_debtor_editor(self, order: Handle, debtor: Debtor) -> str: ...
    def debtor_payment_options(self, editor: str) -> tuple[str, ...]: ...
    def search_payment_terms(self, method: str) -> tuple[PaymentRow, ...]: ...
    def create_payment_term(self, method: str, code: str) -> None: ...
    def save_debtor(self, editor: str, method: str) -> None: ...
    def search_products_from_order(self, order: Handle, sku: str) -> tuple[ProductRow, ...]: ...
    def search_vats(self, name: str) -> tuple[VatRow, ...]: ...
    def create_vat(self, name: str, rate: Decimal) -> None: ...
    def create_product(self, order: Handle, item: Item, gross: Decimal, vat: VatRow) -> None: ...
    def select_product(self, order: Handle, row: ProductRow) -> None: ...
    def complete_line(self, order: Handle, index: int, item: Item, net: Decimal) -> None: ...
    def read_editor(self, handle: Handle) -> Snapshot: ...
    def save_order(self, order: Handle) -> None: ...
    def find_document_rows(self, kind: str, number: str) -> tuple[Snapshot, ...]: ...
    def create_followup_invoice(self, order: Handle) -> Handle: ...
    def apply_invoice_payment(self, invoice: Handle, source: OrderInput) -> None: ...
    def save_invoice(self, invoice: Handle) -> None: ...
    def read_saved_document(self, kind: str, number: str) -> Snapshot: ...
